      title:'ปิดใช้บัญชี '+(r.full_name||r.username)+'?',
      message:'ผู้ใช้นี้จะเข้าสู่ระบบไม่ได้จนกว่าจะเปิดใช้อีกครั้ง',danger:true,okText:'ปิดใช้'
